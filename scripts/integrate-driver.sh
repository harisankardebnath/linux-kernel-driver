#!/usr/bin/env bash
set -euo pipefail

if [ "$#" -ne 1 ]; then
  echo "Usage: $0 <Android-Common-Kernel-repo-root>" >&2
  exit 2
fi

REPO_ROOT="$(cd "$1" && pwd)"
KERNEL="$REPO_ROOT/common"
DRIVER_SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/../driver" && pwd)"
MISC="$KERNEL/drivers/misc"
DEST="$MISC/reverse_exe"

[ -d "$KERNEL/arch/arm64/configs" ] && [ -f "$MISC/Kconfig" ] && [ -f "$MISC/Makefile" ] || {
  echo "Not a recognized Android Common Kernel checkout: $KERNEL" >&2
  exit 1
}

mkdir -p "$DEST"
install -m 0644 "$DRIVER_SRC/reverse_exe.c" "$DEST/"
install -m 0644 "$DRIVER_SRC/Kconfig" "$DEST/"
install -m 0644 "$DRIVER_SRC/Makefile" "$DEST/"

grep -Fq 'source "drivers/misc/reverse_exe/Kconfig"' "$MISC/Kconfig" || \
  printf '\nsource "drivers/misc/reverse_exe/Kconfig"\n' >> "$MISC/Kconfig"
grep -Fq 'CONFIG_REVERSE_EXE' "$MISC/Makefile" || \
  printf '\nobj-$(CONFIG_REVERSE_EXE) += reverse_exe/\n' >> "$MISC/Makefile"

# Do not edit gki_defconfig here. Android's build system validates its
# saved defconfig against the canonical source; injecting a local symbol
# makes savedefconfig fail. Enable the module in the generated .config
# after defconfig has been generated by the build system.

echo "Integrated reverse_exe sources into $KERNEL (defconfig left untouched)"
